IconData adminFaIcon(
  String cls, {
  IconData fallback = const IconData(0xf059, fontFamily: 'ShellFaSolid'),
}) {
  final parts = cls.trim().split(RegExp(r'\s+'));
  final regular = parts.contains('far');
  for (final p in parts) {
    if (p.startsWith('fa-')) {
      final name = p.substring(3);
      final hit = regular ? kAdminFaRegular[name] : kAdminFaSolid[name];
      if (hit != null) return hit;
    }
  }
  return fallback;
}
